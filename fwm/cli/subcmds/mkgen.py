import os
from typing import Optional

import click

from fwm.cli.completion import complete_checkpoint, complete_entry, complete_simpoint_checkpoint, complete_trace
from fwm.cli.fwm import open_repo
from fwm.mkgen.makefile import (
    generate_from_sysroot, generate_from_fesvr_trace, generate_from_checkpoint, generate_from_simpoint
)
from fwm.repo.checkpoint import resolve_checkpoint
from fwm.utils.log import Logger

out_dir_option = click.option("--out-dir", "-o", type=click.Path(file_okay=False), default=".", show_default=True,
                              help="The run directory: an empty or a new directory, or one generated by fwm.")


def done(makefile: str, hint: Optional[str] = None) -> None:
    """Print the path of a generated Makefile, and how to run it."""
    click.echo(makefile)
    Logger.get_logger().info(f"run it with: make -C {os.path.dirname(makefile)} run")
    if hint:
        Logger.get_logger().info(hint)


@click.group()
def mkgen():
    """
    Generate a run directory that begins a simulation: its Makefile, and run.json, which describes what the run uses
    (sysroot, workload, entry point with its metadata, trace, checkpoint).

    \b
    Where to begin:
      from-sysroot     ENTRY       the program from its start, in a fresh copy of its sysroot. It does its real
                                   system calls, so it prints its console and writes its files. Linux only.
      from-fesvr-trace TRACE       the program from its start, replaying a recorded trace: no sysroot needed, any
                                   host. The program prints nothing and writes no file.
      from-checkpoint  CHECKPOINT  the program from a checkpoint, to its end (or for n instructions with -e<n>).
      from-simpoint    CHECKPOINT  a SimPoint checkpoint's interval, for sampled simulation: weigh its results by
                                   the checkpoint's SimPoint weight (`fwm show checkpoint`).

    \b
    Then run `make -C <dir> run`, overriding its variables on the command line, e.g.
      make -C <dir> run SIM=/path/to/721sim SIM_FLAGS_EXTRA="-e100000000" FESVR_FLAGS_EXTRA=+verbose
    SIM defaults to spike, or to the environment variable FWM_SIM_CMD when generated. Every run writes
    final-state.json, each HART's instruction count when the simulation ends; spike leaves it empty when -e stops
    it.
    """


@mkgen.command("from-sysroot")
@click.argument("entry", shell_complete=complete_entry)
@out_dir_option
@click.pass_context
def from_sysroot(ctx, entry, out_dir):
    """
    Run the entry point ENTRY from the start of its program, in a fresh copy of its sysroot.

    Outputs final-state.json, console.stdout and console.stderr (the console is also printed), and the post-run
    sysroot/ with the files the program wrote. It runs on Linux only.
    """
    done(generate_from_sysroot(open_repo(ctx), entry, out_dir))


@mkgen.command("from-fesvr-trace")
@click.argument("trace", shell_complete=complete_trace)
@out_dir_option
@click.pass_context
def from_fesvr_trace(ctx, trace, out_dir):
    """
    Replay TRACE (a trace UUID or prefix, or an entry point with one trace) from the start of its program.

    A replay needs no sysroot and runs on any host; the program prints nothing and writes no file. Outputs
    final-state.json.
    """
    done(generate_from_fesvr_trace(open_repo(ctx), trace, out_dir))


@mkgen.command("from-checkpoint")
@click.argument("checkpoint", shell_complete=complete_checkpoint)
@out_dir_option
@click.pass_context
def from_checkpoint(ctx, checkpoint, out_dir):
    """
    Load CHECKPOINT (<trace>:<name>, or a unique name) and simulate from it to the end of the program, or for n
    instructions with SIM_FLAGS_EXTRA=-e<n>.

    Outputs final-state.json. A run to the end can validate the checkpoint (`fwm repo record-validation`).
    """
    r = open_repo(ctx)
    makefile = generate_from_checkpoint(r, checkpoint, out_dir)
    hint = None
    if resolve_checkpoint(checkpoint).simpoint_interval is not None:
        hint = f"to simulate its SimPoint interval only, use: fwm mkgen from-simpoint {checkpoint}"
    done(makefile, hint)


@mkgen.command("from-simpoint")
@click.argument("checkpoint", shell_complete=complete_simpoint_checkpoint)
@out_dir_option
@click.pass_context
def from_simpoint(ctx, checkpoint, out_dir):
    """
    Load CHECKPOINT (<trace>:<name>, or a unique name), a checkpoint imported with SimPoint information, and simulate
    its SimPoint interval: the Makefile passes -e<interval> to the simulator (override it with INTERVAL=<n>).

    spike exits 1 when -e stops it, so make reports "Error 1": that is how this run normally ends, and
    final-state.json then stays empty. Read the results from the simulator's own statistics.
    """
    done(generate_from_simpoint(open_repo(ctx), checkpoint, out_dir))
