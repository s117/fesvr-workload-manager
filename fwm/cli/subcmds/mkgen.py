import os

import click

from fwm.cli.completion import complete_checkpoint, complete_entry, complete_trace
from fwm.cli.fwm import open_repo
from fwm.mkgen.makefile import generate_record, generate_replay, generate_load
from fwm.utils.log import Logger

_out_dir_option = click.option("--out-dir", "-o", type=click.Path(file_okay=False), default=".", show_default=True,
                               help="The run directory: an empty or a new directory, or one generated by fwm.")


def _done(makefile: str) -> None:
    click.echo(makefile)
    Logger.get_logger().info(f"run it with: make -C {os.path.dirname(makefile)} run")


@click.group()
def mkgen():
    """
    Generate the Makefile of a simulation run in a run directory, and run.json, which describes what the run uses:
    its sysroot, workload, entry point (with its metadata), trace and checkpoint, as `fwm show --json` shows them.

    \b
    Override its variables on the make command line, e.g.
      make run SIM=721sim SIM_FLAGS_EXTRA=-e100000000
    The simulator defaults to spike, or to the environment variable FWM_SIM_CMD.
    """


@mkgen.command()
@click.argument("entry", shell_complete=complete_entry)
@_out_dir_option
@click.pass_context
def record(ctx, entry, out_dir):
    """
    Record a run of the entry point ENTRY in a fresh copy of its sysroot.

    Outputs trace/ (import it with `fwm repo add trace`), final-state.json, console.stdout and console.stderr.
    """
    _done(generate_record(open_repo(ctx), entry, out_dir))


@mkgen.command()
@click.argument("trace", shell_complete=complete_trace)
@click.option("--create-checkpoints", "ckpt_desc", type=click.Path(exists=True, dir_okay=False),
              help='Create the checkpoints of this description file: lines of "<name>: <instruction count>".')
@_out_dir_option
@click.pass_context
def replay(ctx, trace, ckpt_desc, out_dir):
    """
    Replay TRACE (a trace UUID or prefix, or an entry point with one trace), and create checkpoints.

    Outputs final-state.json, and checkpoints/ with --create-checkpoints.
    """
    _done(generate_replay(open_repo(ctx), trace, out_dir, ckpt_desc))


@mkgen.command()
@click.argument("checkpoint", shell_complete=complete_checkpoint)
@_out_dir_option
@click.pass_context
def load(ctx, checkpoint, out_dir):
    """
    Load CHECKPOINT (<trace>:<name>, or a unique name) and simulate from it.

    Outputs final-state.json.
    """
    _done(generate_load(open_repo(ctx), checkpoint, out_dir))
