"""
Reader of `spike --version` output: the build information of spike and of the libfesvr it runs with, for provenance.

The output is generated by riscv-isa-sim's scripts/stamp-build-info.sh: one block per component,

    <title> build information:
      Build hostname  - <value>
      ...
      Version         - <git describe --all --long --dirty>
      Commit          - <git commit>
"""
import re
from typing import Dict

# The fields every block must have, to be taken for build information
REQUIRED_FIELDS = ("Version", "Commit")

_TITLE_RE = re.compile(r"^(?P<title>\S.*) build information:$")
_FIELD_RE = re.compile(r"^\s+(?P<field>\S.*?)\s+- (?P<value>.*)$")

BuildInfo = Dict[str, Dict[str, str]]


class SimVersionError(ValueError):
    pass


def parse_sim_version(text: str) -> BuildInfo:
    """
    Parse `spike --version` output.

    :return: The fields of each block, by block title, e.g. {"spike": {"Version": ..., "Commit": ...}, ...}.
    :raise SimVersionError: The text isn't `--version` output.
    """
    builds: BuildInfo = {}
    current = None
    for number, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        title_match = _TITLE_RE.match(line)
        field_match = _FIELD_RE.match(line)
        if title_match:
            current = builds.setdefault(title_match.group("title"), {})
        elif field_match and current is not None:
            current[field_match.group("field")] = field_match.group("value")
        else:
            raise SimVersionError(f"line {number} is not build information: {line!r}")
    if not builds:
        raise SimVersionError("it holds no build information")
    for title, fields in builds.items():
        missing = [f for f in REQUIRED_FIELDS if f not in fields]
        if missing:
            raise SimVersionError(f"the build information of {title} has no {', '.join(missing)}")
    return builds


def read_sim_version(path: str) -> str:
    """
    Read a file of `spike --version` output, and check it.

    :return: Its text.
    :raise SimVersionError: The file isn't `--version` output.
    """
    with open(path, "r", errors="replace") as f:
        text = f.read()
    parse_sim_version(text)
    return text
