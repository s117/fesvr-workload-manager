"""
Generation of the Makefiles that run the simulator. For repository users (fwm mkgen): from a sysroot, from a FESVR
trace, from a checkpoint, or from a SimPoint checkpoint for one interval. For the repository's creator (fwm repo
bootstrap): record a run of an entry point, or replay a trace to create checkpoints. Each Makefile has a single target,
run, which removes its previous outputs first.
Next to it, run.json describes what the run uses (see run_json.py).
"""
import itertools
import json
import os
import re
import shlex
import shutil
import sys
from datetime import datetime
from importlib import resources
from typing import Any, Dict, Optional

from fwm.data_loader.ckpt_desc import read_ckpt_desc, CkptDescError
from fwm.database.schema import NativeEntry, DecoupledTrace, DecoupledCheckpoint
from fwm.mkgen.run_json import RUN_JSON, describe_run
from fwm.repo.errors import FwmValidationError, NotFoundError
from fwm.repo.lookup import (
    entry_target_cwd, entry_target_path, get_entry, resolve_checkpoint, resolve_trace, trace_harts
)
from fwm.repo.repo import Repo
from fwm.version import fwm_version

MAKEFILE = "Makefile"
_GENERATED_MARK = "# Generated by fwm"
# The header line that says what a run directory is for, as JSON (see read_run_info())
_RUN_INFO_MARK = "# fwm-run: "


def make_escape(value: str) -> str:
    """Escape a value written into a Makefile variable: "$" and "#" are special to make."""
    return value.replace("$", "$$").replace("#", r"\#")


def shell_value(value: str) -> str:
    """
    Quote a value for the shell, then escape it for make. A variable holding it can be joined with more text in a
    recipe: $(RUN)/trace becomes '/a b'/trace, which the shell reads as one word.
    """
    if "\n" in value:
        raise FwmValidationError(f"a Makefile can't hold a value with a newline: {value!r}")
    return make_escape(shlex.quote(value))


def _sim_command() -> str:
    return os.environ.get("FWM_SIM_CMD", "spike")


def _fwm_command() -> str:
    """How the Makefile runs fwm: this interpreter, so it works where fwm is not on PATH (e.g. a batch job)."""
    return f"{shlex.quote(sys.executable)} -m fwm"


def _render(template: str, values: Dict[str, str]) -> str:
    text = resources.files("fwm.mkgen").joinpath("templates", template).read_text()
    placeholders = set(re.findall(r"@([A-Z_]+)@", text))
    assert placeholders <= values.keys(), f"unfilled placeholders in {template}: {placeholders - values.keys()}"
    for key in placeholders:
        text = text.replace(f"@{key}@", values[key])
    return text


def prepare_run_dir(out_dir: str, kind: str) -> str:
    """
    Create the run directory, or check that an existing one can be reused: it must be empty, or have been generated by
    fwm for a run of the same kind, so that a run never mixes with unrelated files or with the outputs of another kind
    of run (which its Makefile doesn't remove).

    :param kind: The kind of the run (see read_run_info()).
    :return: Its absolute path.
    """
    out_dir = os.path.abspath(out_dir)
    shell_value(out_dir)  # reject what a Makefile can't hold, before creating anything
    if os.path.exists(out_dir):
        if not os.path.isdir(out_dir):
            raise FwmValidationError(f"{out_dir} is not a directory")
        if os.listdir(out_dir):
            makefile = os.path.join(out_dir, MAKEFILE)
            generated = False
            if os.path.isfile(makefile):
                with open(makefile) as f:
                    generated = f.readline().startswith(_GENERATED_MARK)
            if not generated:
                raise FwmValidationError(
                    f"{out_dir} is not empty and not a run directory of fwm: use an empty or a new directory")
            previous = (read_run_info(out_dir) or {}).get("kind")
            if previous != kind:
                raise FwmValidationError(
                    f"{out_dir} is the run directory of a {previous or 'former'} run, whose outputs this {kind} "
                    f"run wouldn't remove: use an empty or a new directory")
    else:
        os.makedirs(out_dir)
    return out_dir


def read_run_info(run_dir: str) -> Optional[Dict[str, str]]:
    """
    What a run directory generated by fwm is for: its kind and what it uses, e.g.
    {"kind": "from-sysroot", "entry": ...}, {"kind": "from-fesvr-trace", "trace": ...} or
    {"kind": "from-checkpoint", "trace": ..., "checkpoint": ...}. The kinds are those of fwm mkgen (from-sysroot,
    from-fesvr-trace, from-checkpoint, from-simpoint) and of fwm repo bootstrap mkgen ("record" for record-fesvr-trace,
    create-checkpoints). They are stored in run directories: keep them when commands are renamed.

    :return: None if the directory has no Makefile generated by fwm with this information.
    """
    try:
        with open(os.path.join(run_dir, MAKEFILE)) as f:
            for line in itertools.islice(f, 10):
                if line.startswith(_RUN_INFO_MARK):
                    return json.loads(line[len(_RUN_INFO_MARK):])
    except (OSError, ValueError):
        pass
    return None


def _write_makefile(repo: Repo, run_dir: str, body_template: str, values: Dict[str, str], run_info: Dict[str, str],
                    subjects: Dict[str, Any]) -> str:
    """
    Write the run directory's run.json, then its Makefile (which marks a complete generation).

    :param subjects: What the run uses, from describe_run().
    """
    date = datetime.now().astimezone().isoformat(timespec="seconds")
    command = " ".join(shlex.quote(a) for a in ["fwm"] + sys.argv[1:])
    description = {
        "kind": run_info["kind"],
        "generated": {"time": date, "command": command, "fwm_version": fwm_version(), "repo": repo.path,
                      "sim": _sim_command()},
        **subjects,
    }
    with open(os.path.join(run_dir, RUN_JSON), "w") as f:
        json.dump(description, f, indent=2)
        f.write("\n")

    values = {
        "RUN_INFO": json.dumps(run_info),
        "DATE": date,
        "COMMAND": command,
        "SIM": make_escape(_sim_command()),
        "RUN": shell_value(run_dir),
        **values,
    }
    path = os.path.join(run_dir, MAKEFILE)
    with open(path, "w") as f:
        f.write(_render("header.mk", values) + "\n" + _render(body_template, values))
    return path


def _sysroot_run_values(repo: Repo, entry: NativeEntry) -> Dict[str, str]:
    """The values of a Makefile that runs an entry point in a fresh spawn of its sysroot."""
    stdin_file = entry_target_path(entry, entry.stdin_file) if entry.stdin_file is not None else ""
    return {
        "ENTRY": entry.name,
        "FWM": make_escape(_fwm_command()),
        "REPO": shell_value(repo.path),
        "SYSROOT_NAME": shell_value(entry.sysroot.name),
        "MEM": str(entry.mem_mb),
        "NPROCS": str(entry.nprocs),
        "CWD": shell_value(entry_target_cwd(entry)),
        "BOOT_ELF": shell_value(entry.boot_elf),
        "APP_CMD": make_escape(shlex.join(shlex.split(entry.command))),
        # left empty when there is none: the Makefile tests it with $(if ...)
        "STDIN_FILE": shell_value(stdin_file) if stdin_file else "",
    }


def _trace_values(repo: Repo, trace: DecoupledTrace) -> Dict[str, str]:
    return {
        "ENTRY": trace.native_entry.name,
        "TRACE_UUID": str(trace.uuid),
        "TRACE_DIR": shell_value(repo.trace_dir(trace.uuid)),
        "MEM": str(trace.mem_mb),
        "HARTS": str(trace.num_harts),
    }


def _checkpoint_values(repo: Repo, ckpt: DecoupledCheckpoint) -> Dict[str, str]:
    return {
        **_trace_values(repo, ckpt.trace),
        "CHECKPOINT_NAME": ckpt.name,
        "CHECKPOINT": shell_value(repo.checkpoint_path(ckpt.trace.uuid, ckpt.name)),
    }


def _checkpoint_run_info(kind: str, ckpt: DecoupledCheckpoint) -> Dict[str, str]:
    return {"kind": kind, "trace": str(ckpt.trace.uuid), "checkpoint": ckpt.name}


# --- the runs of repository users (fwm mkgen)


def generate_from_sysroot(repo: Repo, entry_name: str, out_dir: str) -> str:
    """
    Generate the Makefile that runs an entry point in a fresh copy of its sysroot, from the start of the program.

    :return: The path of the Makefile.
    """
    entry: NativeEntry = get_entry(entry_name)
    run_dir = prepare_run_dir(out_dir, "from-sysroot")
    return _write_makefile(repo, run_dir, "from-sysroot.mk", _sysroot_run_values(repo, entry),
                           run_info={"kind": "from-sysroot", "entry": entry.name},
                           subjects=describe_run(repo, entry))


def generate_from_fesvr_trace(repo: Repo, trace_ref: str, out_dir: str) -> str:
    """
    Generate the Makefile that replays a trace from the start of the program.

    :return: The path of the Makefile.
    """
    trace = resolve_trace(trace_ref)
    run_dir = prepare_run_dir(out_dir, "from-fesvr-trace")
    return _write_makefile(repo, run_dir, "from-fesvr-trace.mk", _trace_values(repo, trace),
                           run_info={"kind": "from-fesvr-trace", "trace": str(trace.uuid)},
                           subjects=describe_run(repo, trace.native_entry, trace))


def generate_from_checkpoint(repo: Repo, ckpt_ref: str, out_dir: str) -> str:
    """
    Generate the Makefile that loads a checkpoint and simulates from it to the end of the program.

    :return: The path of the Makefile.
    """
    ckpt = resolve_checkpoint(ckpt_ref)
    run_dir = prepare_run_dir(out_dir, "from-checkpoint")
    return _write_makefile(repo, run_dir, "from-checkpoint.mk", _checkpoint_values(repo, ckpt),
                           run_info=_checkpoint_run_info("from-checkpoint", ckpt),
                           subjects=describe_run(repo, ckpt.trace.native_entry, ckpt.trace, ckpt))


def generate_from_simpoint(repo: Repo, ckpt_ref: str, out_dir: str) -> str:
    """
    Generate the Makefile that loads a SimPoint checkpoint and simulates its interval.

    :return: The path of the Makefile.
    :raise FwmValidationError: The checkpoint has no SimPoint information.
    """
    ckpt = resolve_checkpoint(ckpt_ref)
    if ckpt.simpoint_interval is None:
        raise FwmValidationError(
            f"checkpoint {ckpt.trace.uuid}:{ckpt.name} has no SimPoint information (it was imported without "
            f"--simpoint-info): simulate from it with `fwm mkgen from-checkpoint`")
    run_dir = prepare_run_dir(out_dir, "from-simpoint")
    values = {
        **_checkpoint_values(repo, ckpt),
        "SIMPOINT_INDEX": str(ckpt.simpoint_index),
        "SIMPOINT_WEIGHT": str(ckpt.simpoint_weight),
        "INTERVAL": str(ckpt.simpoint_interval),
    }
    return _write_makefile(repo, run_dir, "from-simpoint.mk", values,
                           run_info=_checkpoint_run_info("from-simpoint", ckpt),
                           subjects=describe_run(repo, ckpt.trace.native_entry, ckpt.trace, ckpt))


# --- the runs that bootstrap the repository (fwm repo bootstrap mkgen)


def generate_record(repo: Repo, entry_name: str, out_dir: str) -> str:
    """
    Generate the Makefile that records a run of an entry point, to import as a trace.

    :return: The path of the Makefile.
    """
    entry: NativeEntry = get_entry(entry_name)
    run_dir = prepare_run_dir(out_dir, "record")
    return _write_makefile(repo, run_dir, "record.mk", _sysroot_run_values(repo, entry),
                           run_info={"kind": "record", "entry": entry.name}, subjects=describe_run(repo, entry))


def generate_create_checkpoints(repo: Repo, trace_ref: str, ckpt_desc: str, out_dir: str) -> str:
    """
    Generate the Makefile that replays a trace and creates the checkpoints of a description file, to import.

    :return: The path of the Makefile.
    """
    trace = resolve_trace(trace_ref)
    if trace.num_harts != 1:
        raise FwmValidationError(
            f"trace {trace.uuid} has {trace.num_harts} HARTs: FESVR creates checkpoints of a single HART only")
    try:
        checkpoints = read_ckpt_desc(ckpt_desc)
    except OSError as e:
        raise NotFoundError(f"cannot read the checkpoint description {ckpt_desc}: {e}")
    except CkptDescError as e:
        raise FwmValidationError(f"invalid checkpoint description {ckpt_desc}: {e}")
    instret = trace_harts(trace)[0].instret
    if instret is not None:
        beyond = [(name, count) for name, count in checkpoints if count >= instret]
        if beyond:
            raise FwmValidationError(
                f"the program of trace {trace.uuid} exits after {instret} instructions, so these checkpoints would be "
                f"at or after its exit, where spike creates none: " +
                ", ".join(f"{name} ({count})" for name, count in beyond))

    run_dir = prepare_run_dir(out_dir, "create-checkpoints")
    shutil.copyfile(ckpt_desc, os.path.join(run_dir, "ckpt.desc"))
    return _write_makefile(repo, run_dir, "create-checkpoints.mk", _trace_values(repo, trace),
                           run_info={"kind": "create-checkpoints", "trace": str(trace.uuid)},
                           subjects=describe_run(repo, trace.native_entry, trace, requested=checkpoints))
