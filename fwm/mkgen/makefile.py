"""
Generation of the Makefiles that run the simulator: record a run of an entry point, replay a trace (optionally creating
checkpoints), or load a checkpoint. Each Makefile has a single target, run, which removes its previous outputs first.
"""
import os
import re
import shlex
import shutil
import sys
from datetime import datetime
from importlib import resources
from typing import Dict, Optional

from fwm.data_loader.ckpt_desc import parse_ckpt_desc, CkptDescError
from fwm.database.schema import NativeEntry, DecoupledTrace
from fwm.repo.checkpoint import resolve_checkpoint
from fwm.repo.entry import get_entry, entry_target_cwd, entry_target_path
from fwm.repo.errors import FwmValidationError, NotFoundError
from fwm.repo.repo import Repo
from fwm.repo.trace import resolve_trace, trace_harts

MAKEFILE = "Makefile"
_GENERATED_MARK = "# Generated by fwm"


def make_escape(value: str) -> str:
    """Escape a value written into a Makefile variable: "$" and "#" are special to make."""
    return value.replace("$", "$$").replace("#", r"\#")


def _sim_command() -> str:
    return os.environ.get("FWM_SIM_CMD", "spike")


def _fwm_command() -> str:
    """How the Makefile runs fwm: this interpreter, so it works where fwm is not on PATH (e.g. a batch job)."""
    return f"{shlex.quote(sys.executable)} -m fwm"


def _render(template: str, values: Dict[str, str]) -> str:
    text = resources.files("fwm.mkgen").joinpath("templates", template).read_text()
    placeholders = set(re.findall(r"@([A-Z_]+)@", text))
    assert placeholders <= values.keys(), f"unfilled placeholders in {template}: {placeholders - values.keys()}"
    for key in placeholders:
        text = text.replace(f"@{key}@", values[key])
    return text


def prepare_run_dir(out_dir: str) -> str:
    """
    Create the run directory, or check that an existing one can be reused: it must be empty, or have been generated by
    fwm (it holds an fwm Makefile), so that a run never mixes with unrelated files.

    :return: Its absolute path.
    """
    out_dir = os.path.abspath(out_dir)
    if os.path.exists(out_dir):
        if not os.path.isdir(out_dir):
            raise FwmValidationError(f"{out_dir} is not a directory")
        if os.listdir(out_dir):
            makefile = os.path.join(out_dir, MAKEFILE)
            generated = False
            if os.path.isfile(makefile):
                with open(makefile) as f:
                    generated = f.readline().startswith(_GENERATED_MARK)
            if not generated:
                raise FwmValidationError(
                    f"{out_dir} is not empty and not a run directory of fwm: use an empty or a new directory")
    else:
        os.makedirs(out_dir)
    return out_dir


def _write_makefile(run_dir: str, body_template: str, values: Dict[str, str]) -> str:
    values = {
        "DATE": datetime.now().astimezone().isoformat(timespec="seconds"),
        "COMMAND": " ".join(shlex.quote(a) for a in ["fwm"] + sys.argv[1:]),
        "SIM": make_escape(_sim_command()),
        "RUN": make_escape(run_dir),
        **values,
    }
    path = os.path.join(run_dir, MAKEFILE)
    with open(path, "w") as f:
        f.write(_render("header.mk", values) + "\n" + _render(body_template, values))
    return path


def generate_record(repo: Repo, entry_name: str, out_dir: str) -> str:
    """
    Generate the Makefile that records a run of an entry point.

    :return: The path of the Makefile.
    """
    entry: NativeEntry = get_entry(entry_name)
    run_dir = prepare_run_dir(out_dir)
    stdin_file = entry_target_path(entry, entry.stdin_file) if entry.stdin_file is not None else ""
    return _write_makefile(run_dir, "record.mk", {
        "ENTRY": entry.name,
        "FWM": make_escape(_fwm_command()),
        "REPO": make_escape(repo.path),
        "SYSROOT_NAME": entry.sysroot.name,
        "MEM": str(entry.mem_mb),
        "NPROCS": str(entry.nprocs),
        "CWD": make_escape(entry_target_cwd(entry)),
        "BOOT_ELF": make_escape(entry.boot_elf),
        "APP_CMD": make_escape(shlex.join(shlex.split(entry.command))),
        "STDIN_FILE": make_escape(stdin_file),
    })


def _trace_values(repo: Repo, trace: DecoupledTrace) -> Dict[str, str]:
    return {
        "ENTRY": trace.native_entry.name,
        "TRACE_UUID": str(trace.uuid),
        "TRACE_DIR": make_escape(repo.trace_dir(trace.uuid)),
        "MEM": str(trace.mem_mb),
        "HARTS": str(trace.num_harts),
    }


def generate_replay(repo: Repo, trace_ref: str, out_dir: str, ckpt_desc: Optional[str] = None) -> str:
    """
    Generate the Makefile that replays a trace, and creates the checkpoints of a description file if one is given.

    :return: The path of the Makefile.
    """
    trace = resolve_trace(trace_ref)
    if ckpt_desc is None:
        return _write_makefile(prepare_run_dir(out_dir), "replay.mk", _trace_values(repo, trace))

    if trace.num_harts != 1:
        raise FwmValidationError(
            f"trace {trace.uuid} has {trace.num_harts} HARTs: FESVR creates checkpoints of a single HART only")
    try:
        with open(ckpt_desc) as f:
            text = f.read()
    except OSError as e:
        raise NotFoundError(f"cannot read the checkpoint description {ckpt_desc}: {e}")
    try:
        checkpoints = parse_ckpt_desc(text)
    except CkptDescError as e:
        raise FwmValidationError(f"invalid checkpoint description {ckpt_desc}: {e}")
    instret = trace_harts(trace)[0].instret
    if instret is not None:
        beyond = [(name, count) for name, count in checkpoints if count >= instret]
        if beyond:
            raise FwmValidationError(
                f"the program of trace {trace.uuid} stops after {instret} instructions, so these checkpoints can't be "
                f"created: " + ", ".join(f"{name} ({count})" for name, count in beyond))

    run_dir = prepare_run_dir(out_dir)
    shutil.copyfile(ckpt_desc, os.path.join(run_dir, "ckpt.desc"))
    return _write_makefile(run_dir, "create-checkpoints.mk", _trace_values(repo, trace))


def generate_load(repo: Repo, ckpt_ref: str, out_dir: str) -> str:
    """
    Generate the Makefile that loads a checkpoint and simulates from it.

    :return: The path of the Makefile.
    """
    ckpt = resolve_checkpoint(ckpt_ref)
    return _write_makefile(prepare_run_dir(out_dir), "load.mk", {
        **_trace_values(repo, ckpt.trace),
        "CHECKPOINT_NAME": ckpt.name,
        "CHECKPOINT": make_escape(repo.checkpoint_path(ckpt.trace.uuid, ckpt.name)),
    })
